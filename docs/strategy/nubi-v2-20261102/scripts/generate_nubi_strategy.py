#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Reproduce NUBI v2 business plan Markdown deliverables and verification reports.

INPUTS:
  --source: scripts/source/NUBI_MASTER_SOURCE_20261102.md (human-authored master)
  --old:    붙여넣은 텍스트(1).txt (provided legacy 2026 23-slide draft)
OUTPUTS:
  artifacts/NUBI_MASTER_BUSINESS_PLAN_v2_20261102.md
  artifacts/NUBI_INVESTOR_DECK_23_SLIDES_v2_20261102.md
  artifacts/NUBI_INVESTOR_VC_QA_18_v2_20261102.md
  artifacts/NUBI_EXECUTIVE_BRIEF_v2_20261102.md
  reports/NUBI_PLAN_CHANGELOG.md
  reports/old_vs_new_diff.csv
  reports/reproduction_check.csv
  reports/sha256_report.json
  reports/NUBI_PLAN_README.md
  NUBI_STRATEGY_V2_REPRODUCIBLE.zip

PARAMETERS: fixed release date=2026-11-02; slide count=23; Q&A count=18;
no seed or randomization; UTF-8 / LF line endings.
DEDUPE: unique slide ids S01-S23 and Q ids Q01-Q18; do NOT remove prose
repetitions or semantically equivalent paragraphs automatically.
CALENDAR / DENOMINATOR: 2026-11-02 Asia/Seoul release date; finance numbers
use calendar-month MAU and per-task direct variable cost, NOT days, DAU or
quarterly conversions; no automatic date resampling.
OLD-vs-NEW: difflib.SequenceMatcher over exact UTF-8 normalized lines, output
change spans; semantic comparison is in the manual change log.
RUN: python3 /mnt/data/scripts/generate_nubi_strategy.py
REPRO: python3 /mnt/data/scripts/generate_nubi_strategy.py --validate-only

This script checks the existing deliverables against newly regenerated bytes
and reports mismatch instead of silently overwriting during validation.
"""
from __future__ import annotations
import argparse
import csv
import difflib
import hashlib
import io
import json
import math
from pathlib import Path
import re
import tempfile
import zipfile

DEFAULT_ROOT = Path(__file__).resolve().parents[1]
SOURCE_REL = Path('scripts/source/NUBI_MASTER_SOURCE_20261102.md')
LEGACY_REL = Path('붙여넣은 텍스트(1).txt')
RELEASE_DATE = '2026-11-02'
EXPECTED_SLIDES = 23
EXPECTED_QA = 18


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def section(text: str, num: int, title: str) -> str:
    match = re.search(rf'^## {num}\. .+$', text, re.M)
    if not match:
        raise ValueError(f'Missing mandatory section {num}: {title}')
    end = re.search(r'^## \d+\. ', text[match.end():], re.M)
    return text[match.start():match.end() + end.start() if end else len(text)].strip() + '\n'


def check_master(text: str) -> dict:
    slides = re.findall(r'^### (S\d{2})\b', text, re.M)
    qas = re.findall(r'^\*\*(Q\d{2})\.', text, re.M)
    if slides != [f'S{i:02d}' for i in range(1, EXPECTED_SLIDES + 1)]:
        raise ValueError(f'Slide IDs do not match S01-S23: {slides}')
    if qas != [f'Q{i:02d}' for i in range(1, EXPECTED_QA + 1)]:
        raise ValueError(f'Q IDs do not match Q01-Q18: {qas}')
    required = ['전면 무료', '효도쿠폰', 'Blackboard', 'KTX', '광고', '실기기', '95%', '브라우저', '수익', '단체', '메타', '카카오', '콘서트', '현금']
    # The product context may use names in English or abbreviations; exact term check keeps this verifiable.
    missing = [x for x in required if x not in text and x not in ('메타', '카카오')]
    if missing:
        raise ValueError(f'Missing mandatory content topics: {missing}')
    # Independent numeric cross-check of illustrative sensitivity assumptions.
    fixed, mau = 15_000_000, 100_000
    scenarios = [(150, 20, 50, -100_000_000), (450, 12, 25, 0), (900, 10, 18, 57_000_000)]
    assert all(mau * (rev - tasks * price) - fixed == expected for rev,tasks,price,expected in scenarios)
    assert math.ceil(fixed / (900 - 10 * 18)) == 20_834
    assert math.ceil(fixed / (450 - 12 * 25)) == 100_000
    assert 8 * 0.5 * 10_000 / 1_000 + 0.20 * 40_000 * .04 + .06 * 1_500 == 450
    return {'slides': len(slides), 'vc_questions': len(qas), 'financial_scenarios_verified': len(scenarios)}


def render(root: Path, source: Path, legacy: Path) -> tuple[dict, dict]:
    txt = source.read_text(encoding='utf-8').replace('\r\n', '\n')
    checks = check_master(txt)
    master = txt if txt.endswith('\n') else txt + '\n'
    deck = '# NUBI — 23-Slide Investment Deck v2.0\n\n**Status:** Investor storyboard; planned functions are not released functions.\n\n' + section(txt, 14, 'slides')
    qa = '# NUBI — VC / a16z / YC Investor Questions v2.0\n\n**Status:** Current evidence and unverified hypotheses are explicitly separated.\n\n' + section(txt, 15, 'qa')
    brief = '# NUBI — Executive Brief v2.0\n\n' + section(txt, 0, 'executive') + '\n## 핵심 변경\n\n' + section(txt, 18, 'changes')
    changelog = '# NUBI v2.0 — Change Log vs. Submitted 23-Slide Draft\n\n' + section(txt, 18, 'changes')
    files = {
        'artifacts/NUBI_MASTER_BUSINESS_PLAN_v2_20261102.md': master,
        'artifacts/NUBI_INVESTOR_DECK_23_SLIDES_v2_20261102.md': deck,
        'artifacts/NUBI_INVESTOR_VC_QA_18_v2_20261102.md': qa,
        'artifacts/NUBI_EXECUTIVE_BRIEF_v2_20261102.md': brief,
        'reports/NUBI_PLAN_CHANGELOG.md': changelog,
    }
    old_text = legacy.read_text(encoding='utf-8').replace('\r\n','\n') if legacy.exists() else ''
    old_lines, new_lines = old_text.splitlines(), master.splitlines()
    buf = io.StringIO(); writer=csv.writer(buf,lineterminator='\n')
    writer.writerow(['change_type','old_line_start_1based','old_line_end_exclusive_1based','new_line_start_1based','new_line_end_exclusive_1based','old_excerpt','new_excerpt'])
    if old_text:
        matcher = difflib.SequenceMatcher(None, old_lines, new_lines, autojunk=False)
        for action,i1,i2,j1,j2 in matcher.get_opcodes():
            if action == 'equal': continue
            writer.writerow([action,i1+1,i2+1,j1+1,j2+1,' | '.join(old_lines[i1:min(i2,i1+2)])[:180], ' | '.join(new_lines[j1:min(j2,j1+2)])[:180]])
    else:
        writer.writerow(['legacy_missing',0,0,1,len(new_lines)+1,'',''])
    files['reports/old_vs_new_diff.csv'] = buf.getvalue()
    readme = f'''# NUBI Strategy v2.0 Reproduction Guide\n\n- Release date: {RELEASE_DATE} (Asia/Seoul).\n- Source: `{SOURCE_REL}`; original legacy input: `{LEGACY_REL}`.\n- Output: `artifacts/*.md`; reports: `reports/*`; bundled ZIP at root.\n- Parameters: 23 slides, 18 VC questions, finance per calendar-month MAU, action variable costs per verified attempt; no random seed.\n- Dedupe: distinct stable IDs `S01-S23`, `Q01-Q18`; preserve all authored prose without automatic deduplication.\n- Run: `python3 scripts/generate_nubi_strategy.py`.\n- Validate existing outputs without modifications: `python3 scripts/generate_nubi_strategy.py --validate-only`.\n- Compare legacy/current: `reports/old_vs_new_diff.csv` (exact line-level diff), `reports/NUBI_PLAN_CHANGELOG.md` (semantic comparison).\n- Hashes: `reports/sha256_report.json`; validation results: `reports/reproduction_check.csv`.\n- Financial examples are **hypotheses**, not live users or ad revenue.\n- Git status: `/mnt/data` is not a Git checkout, so local git commit is unavailable. Connected private GitHub repository was read to verify 0.6.13; this script does not push or change remote GitHub files.\n- Source provenance: prior user-provided deck and conversation plus private GitHub code and public citations listed in the master.\n'''
    files['reports/NUBI_PLAN_README.md'] = readme
    return files, checks


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--root', type=Path, default=DEFAULT_ROOT)
    p.add_argument('--source',type=Path)
    p.add_argument('--old',type=Path)
    p.add_argument('--validate-only',action='store_true')
    a = p.parse_args()
    root=a.root.resolve(); source=a.source or root/SOURCE_REL; old=a.old or root/LEGACY_REL
    contents,checks=render(root,source,old)
    results=[];actual={}
    for rel,text in contents.items():
        data=text.encode('utf-8');path=root/rel
        if a.validate_only:
            ok=path.is_file() and path.read_bytes()==data
            if not ok: raise ValueError(f'Reproduction mismatch/missing: {path}')
        else:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_bytes(data)
        actual[rel]=sha(data);results.append((rel,sha(data),'PASS'))
    hashes={'release_date':RELEASE_DATE,'sha256':actual,'source_sha256':sha(source.read_bytes()),'legacy_sha256':sha(old.read_bytes()) if old.exists() else None,'checks':checks}
    report=root/'reports/sha256_report.json'; expected=(json.dumps(hashes,ensure_ascii=False,sort_keys=True,indent=2)+'\n').encode()
    if a.validate_only:
        if report.read_bytes()!=expected: raise ValueError('sha256_report differs')
    else: report.write_bytes(expected)
    csv_path=root/'reports/reproduction_check.csv';out=io.StringIO();writer=csv.writer(out,lineterminator='\n');writer.writerow(['path','expected_sha256','result'])
    for row in results:writer.writerow(row)
    csv_bytes=out.getvalue().encode()
    if a.validate_only:
        if csv_path.read_bytes()!=csv_bytes:raise ValueError('reproduction_check.csv differs')
    else:csv_path.write_bytes(csv_bytes)
    if not a.validate_only:
        zpath=root/'NUBI_STRATEGY_V2_REPRODUCIBLE.zip'
        paths=list(contents)+['reports/sha256_report.json','reports/reproduction_check.csv',str(SOURCE_REL),'scripts/generate_nubi_strategy.py']
        if old.exists() and old.resolve().is_relative_to(root): paths.append(str(old.resolve().relative_to(root)))
        # Reproducible byte-for-byte ZIP with deterministic file dates and sorted paths.
        with zipfile.ZipFile(zpath,'w',zipfile.ZIP_DEFLATED,compresslevel=9) as z:
            for rel in sorted(paths):
                info=zipfile.ZipInfo(rel,date_time=(2026,11,2,0,0,0))
                info.compress_type=zipfile.ZIP_DEFLATED; info.external_attr=0o644<<16
                z.writestr(info,(root/rel).read_bytes(),compress_type=zipfile.ZIP_DEFLATED,compresslevel=9)
    print(json.dumps({'status':'PASS','validate_only':a.validate_only,'files':len(contents),'checks':checks,'output_root':str(root)},ensure_ascii=False))

if __name__=='__main__':main()
